CREATE TABLE DIM_CLIENTE (
    cliente_key NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    customerNumber NUMBER(10) NOT NULL,
    customerName VARCHAR2(100 CHAR) NOT NULL,
    contactFirstName VARCHAR2(60 CHAR),
    contactLastName VARCHAR2(60 CHAR),
    city VARCHAR2(60 CHAR),
    state VARCHAR2(60 CHAR),
    country VARCHAR2(60 CHAR),
    creditLimit NUMBER(12,2),

    CONSTRAINT pk_dim_cliente PRIMARY KEY (cliente_key),
    CONSTRAINT uq_dim_cliente_customer UNIQUE (customerNumber)
);
