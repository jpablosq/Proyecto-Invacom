
CREATE TABLE DIM_PRODUCTO (
    producto_key NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    productCode VARCHAR2(20 CHAR) NOT NULL,
    productName VARCHAR2(100 CHAR) NOT NULL,
    productLine VARCHAR2(60 CHAR),
    productScale VARCHAR2(15 CHAR),
    productVendor VARCHAR2(100 CHAR),
    descripcion_linea VARCHAR2(1200 CHAR),
    buyPrice NUMBER(12,2),
    MSRP NUMBER(12,2),

    CONSTRAINT pk_dim_producto PRIMARY KEY (producto_key),
    CONSTRAINT uq_dim_producto_code UNIQUE (productCode)
);
