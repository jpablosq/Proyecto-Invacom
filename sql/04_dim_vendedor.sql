    jobTitle VARCHAR2(100 CHAR),
    email VARCHAR2(120 CHAR),
    officeCode VARCHAR2(10 CHAR),
    ciudad_oficina VARCHAR2(60 CHAR),
    pais_oficina VARCHAR2(60 CHAR),
    territorio_oficina VARCHAR2(30 CHAR),

    CONSTRAINT pk_dim_vendedor PRIMARY KEY (vendedor_key),
    CONSTRAINT uq_dim_vendedor_employee UNIQUE (employeeNumber)
