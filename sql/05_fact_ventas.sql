
CREATE TABLE FACT_VENTAS (
    venta_key NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    orderNumber NUMBER(10) NOT NULL,
    orderLineNumber NUMBER(10) NOT NULL,

    cliente_key NUMBER NOT NULL,
    producto_key NUMBER NOT NULL,
    fecha_key NUMBER(8) NOT NULL,
    vendedor_key NUMBER NOT NULL,

    cantidad NUMBER(10) NOT NULL,
    precio_unitario NUMBER(12,2) NOT NULL,
    importe_total NUMBER(14,2) NOT NULL,
    estado_pedido VARCHAR2(30 CHAR) NOT NULL,
    costo_total NUMBER(14,2),
    margen NUMBER(14,2),

    CONSTRAINT pk_fact_ventas
        PRIMARY KEY (venta_key),

    CONSTRAINT uq_fact_ventas_linea
        UNIQUE (orderNumber, orderLineNumber),

    CONSTRAINT fk_ventas_cliente
        FOREIGN KEY (cliente_key)
        REFERENCES DIM_CLIENTE(cliente_key),

    CONSTRAINT fk_ventas_producto
        FOREIGN KEY (producto_key)
        REFERENCES DIM_PRODUCTO(producto_key),

    CONSTRAINT fk_ventas_fecha
        FOREIGN KEY (fecha_key)
        REFERENCES DIM_FECHA(fecha_key),

    CONSTRAINT fk_ventas_vendedor
        FOREIGN KEY (vendedor_key)
        REFERENCES DIM_VENDEDOR(vendedor_key),

    CONSTRAINT ck_ventas_cantidad
        CHECK (cantidad > 0),

    CONSTRAINT ck_ventas_precio
        CHECK (precio_unitario >= 0)
);
