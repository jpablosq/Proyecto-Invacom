
CREATE TABLE FACT_PAGOS (
    pago_key NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    cliente_key NUMBER NOT NULL,
    fecha_key NUMBER(8) NOT NULL,
    checkNumber VARCHAR2(50 CHAR) NOT NULL,
    monto NUMBER(14,2) NOT NULL,

    CONSTRAINT pk_fact_pagos
        PRIMARY KEY (pago_key),

    CONSTRAINT fk_pagos_cliente
        FOREIGN KEY (cliente_key)
        REFERENCES DIM_CLIENTE(cliente_key),

    CONSTRAINT fk_pagos_fecha
        FOREIGN KEY (fecha_key)
        REFERENCES DIM_FECHA(fecha_key),

    CONSTRAINT uq_fact_pagos
        UNIQUE (cliente_key, checkNumber),

    CONSTRAINT ck_pagos_monto
        CHECK (monto > 0)
);
